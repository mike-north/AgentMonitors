import { randomUUID } from 'node:crypto';
import type {
  AgentMonitorRuntime,
  AgentSessionRecord,
} from '@agentmonitors/core';
import { Command } from 'commander';
import {
  callDaemonAtSocket,
  DaemonConnectionError,
  resolveSocketPath,
} from '../daemon-ipc.js';
import { escapeShellPath } from '../delivery-event-render.js';
import { MAX_TIMER_DELAY_MS, parseIntegerOption } from '../integer-option.js';
import {
  manualDaemonErrorMessage,
  resolveManualDaemonSocketPath,
} from '../manual-daemon.js';
import { reportError } from '../output.js';

export const postCommand = new Command('post')
  .description('Post a message to a session')
  .argument('<body>', 'Message text')
  .requiredOption('--session <id>', 'Recipient session id (see session list)')
  .option(
    '--key <string>',
    'Workspace request key for safe retries (generated by default)',
  )
  .option('--socket <path>', 'Unix domain socket path for the daemon')
  .option(
    '--workspace <path>',
    'Registered workspace for the request key (empty for global scope)',
  )
  .option(
    '--require-ack',
    'Resurface the message until acknowledged or its budget is spent',
  )
  .option(
    '--resurface-after-ms <ms>',
    'Time between delivery and the next offer (default 300000)',
  )
  .option(
    '--max-resurfaces <count>',
    'Resurfaces before needs-attention (default 2)',
  )
  .action(
    async (
      body: string,
      options: {
        session: string;
        socket?: string;
        key?: string;
        workspace?: string;
        requireAck?: boolean;
        resurfaceAfterMs?: string;
        maxResurfaces?: string;
      },
    ) => {
      try {
        const resurfaceAfterMs =
          options.resurfaceAfterMs === undefined
            ? undefined
            : parseIntegerOption(
                '--resurface-after-ms',
                options.resurfaceAfterMs,
                { min: 1, max: MAX_TIMER_DELAY_MS },
              );
        if (resurfaceAfterMs?.ok === false)
          throw new Error(resurfaceAfterMs.message);
        const maxResurfaces =
          options.maxResurfaces === undefined
            ? undefined
            : parseIntegerOption('--max-resurfaces', options.maxResurfaces, {
                min: 0,
                max: 100,
              });
        if (maxResurfaces?.ok === false) throw new Error(maxResurfaces.message);
        const socketPath =
          resolveManualDaemonSocketPath(options.socket) ?? resolveSocketPath();
        let workspacePath = options.workspace;
        if (workspacePath === undefined) {
          const sessions = await callDaemonAtSocket<AgentSessionRecord[]>(
            socketPath,
            'session.list',
            {},
          );
          const recipient = sessions.find(({ id }) => id === options.session);
          if (!recipient)
            throw new Error(`Unknown session: ${options.session}`);
          workspacePath = recipient.workspacePath ?? '';
        }
        const key = options.key ?? randomUUID();
        const input = {
          key,
          workspacePath,
          sessionId: options.session,
          body,
          requireAck: options.requireAck,
          resurfaceAfterMs: resurfaceAfterMs?.value,
          maxResurfaces: maxResurfaces?.value,
        };
        // Both attempts use the same endpoint and workspace key scope.
        const send = () =>
          callDaemonAtSocket<ReturnType<AgentMonitorRuntime['postMessage']>>(
            socketPath,
            'messages.postScoped',
            input,
          );
        const result = await send().catch(async (error: unknown) => {
          if (!(error instanceof DaemonConnectionError) || !error.requestSent)
            throw error;
          try {
            return await send();
          } catch {
            throw new Error(
              `Could not confirm the post. Retry the same command with --key ${escapeShellPath(key)}. Use --workspace ${escapeShellPath(workspacePath)} and --socket ${escapeShellPath(socketPath)} to recover from the original workspace and daemon.`,
            );
          }
        });
        console.log(result.eventId);
        if (result.hookStateRefreshError !== undefined) {
          console.error(
            `Warning: post committed, but hook-state refresh failed: ${result.hookStateRefreshError}`,
          );
        }
      } catch (error) {
        reportError(manualDaemonErrorMessage(error), false);
      }
    },
  );
